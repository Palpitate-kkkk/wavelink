"""Compare production receiver against a separately written stdlib reference."""
import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import platform
import subprocess
import sys
import numpy as np
from validation.reference_receiver import fixture
from wavelink import ofdm_modulate, ofdm_demodulate, qpsk_demodulate
from wavelink.receiver import comb_grid, apply_multipath, zero_force
from wavelink.estimation import TapDomainLS, TapDomainLMMSE
from experiments.density_ber import digest
from experiments.multipath_ber import write_csv
from experiments.captured_tracking_ber import seed_sets


def evaluate(cfg):
    rows = []
    layout = comb_grid(2)
    for seed in cfg['seeds']:
        for variance in cfg['noise_variances']:
            ref = fixture(seed, variance)
            tx = ofdm_modulate(ref['grids'], 16)
            latent, _ = apply_multipath(tx, ref['taps'])
            received = ofdm_demodulate(ref['rx'], 64, 16)[1:]
            pilots = np.asarray(ref['pilots'][1:])
            ls = TapDomainLS(layout, 13).estimate(received, pilots)
            lmmse = TapDomainLMMSE(layout, ref['powers'], max(variance, .05)).estimate(received, pilots)
            difference = lambda a, b: float(np.max(abs(np.asarray(a)-np.asarray(b))))
            r = dict(seed=seed, noise_variance=variance, tx_max_error=difference(tx, ref['tx']),
                     fir_max_error=difference(latent, ref['latent']), fft_max_error=difference(received, ref['received']),
                     ls_max_error=difference(ls, ref['ls']), lmmse_max_error=difference(lmmse, ref['lmmse']))
            for name, h in [('ls', ls), ('lmmse', lmmse)]:
                decoded = qpsk_demodulate(zero_force(received[:, layout.bins(layout.data_tones)], h).ravel())
                r[name+'_decision_mismatches'] = int(np.count_nonzero(decoded != ref[name+'_bits']))
                r[name+'_bit_errors'] = int(np.count_nonzero(decoded != ref['bits']))
                if r[name+'_decision_mismatches']:
                    raise AssertionError('reference decision mismatch')
            if max(r[k] for k in r if k.endswith('_max_error')) > cfg['absolute_tolerance']:
                raise AssertionError('independent numerical crosscheck failed')
            if variance == 0 and r['ls_bit_errors']:
                raise AssertionError('noiseless LS must decode exactly')
            rows.append(r)
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', type=Path, default=Path('experiments/crosscheck.json'))
    parser.add_argument('--output', type=Path, default=Path('results/crosscheck'))
    args = parser.parse_args()
    cfg = json.loads(args.config.read_text())
    if cfg['noise_variances'] != [0., .05] or cfg['absolute_tolerance'] != 2e-10 or len(cfg['seeds']) != 4 or len(set(cfg['seeds'])) != 4:
        raise ValueError('fixed four-root/two-noise numerical protocol required')
    used = set()
    for p in Path('experiments').glob('*.json'):
        if p != args.config: used.update(seed_sets(json.loads(p.read_text())))
    if used & set(cfg['seeds']): raise ValueError('new numerical fixture roots required')
    paths = sorted(Path('src').rglob('*.py'))+sorted(Path('experiments').glob('*.py'))+sorted(Path('experiments').glob('*.json'))+[Path('validation/reference_receiver.py')]
    hashes = {str(p): digest(p) for p in paths}
    rows = evaluate(cfg)
    if any(digest(p) != h for p, h in hashes.items()): raise RuntimeError('source changed')
    args.output.mkdir(parents=True, exist_ok=True)
    write_csv(args.output/'runs.csv', rows)
    meta = dict(source_sha256=hashes, artifact_sha256={'runs.csv': digest(args.output/'runs.csv')}, config=cfg,
                base_commit=subprocess.check_output(['git', 'rev-parse', 'HEAD'], text=True).strip(),
                working_tree_dirty=bool(subprocess.check_output(['git', 'status', '--porcelain'], text=True).strip()),
                command=['python', '-m', 'experiments.crosscheck', *sys.argv[1:]],
                python=platform.python_version(), numpy=np.__version__, platform=platform.platform(),
                finished_at_utc=datetime.now(timezone.utc).isoformat(),
                scope='Numerical cross-implementation checks, NOT new performance evidence. Shared fixtures generated by stdlib only; reference uses dense DFT and pivoted elimination, production NumPy FFT/SVD/solve. No MATLAB/Octave/hardware execution claimed.')
    (args.output/'metadata.json').write_text(json.dumps(meta, indent=2)+'\n')
    print(json.dumps(dict(ok=True, cases=len(rows), maximum_error=max(r[k] for r in rows for k in r if k.endswith('_max_error')))))


if __name__ == '__main__':
    main()
